async function addBirthdays() {
    console.log("🎂 Начинаем добавление дат рождения...");

    try {
        const snapshot = await getDocs(studentsCol);

        let updated = 0;
        let alreadyExists = 0;
        let notFound = 0;

        for (const [name, birthday] of Object.entries(birthdayDates)) {

            const studentDoc = snapshot.docs.find(
                d => d.data().name === name
            );

            if (!studentDoc) {
                console.warn(
                    `⚠️ Ученик не найден: ${name}`
                );

                notFound++;
                continue;
            }

            const data = studentDoc.data();

            // Если дата уже есть — ничего не меняем
            if (data.birthday) {
                console.log(
                    `⏭️ Уже есть: ${name} → ${data.birthday}`
                );

                alreadyExists++;
                continue;
            }

            await updateDoc(
                doc(
                    studentsCol,
                    studentDoc.id
                ),
                {
                    birthday: birthday
                }
            );

            console.log(
                `✅ Добавлено: ${name} → ${birthday}`
            );

            updated++;
        }

        console.log("");
        console.log("=================================");
        console.log("🎂 ИМПОРТ ЗАВЕРШЁН");
        console.log("=================================");
        console.log(`✅ Добавлено: ${updated}`);
        console.log(`⏭️ Уже было: ${alreadyExists}`);
        console.log(`⚠️ Не найдено: ${notFound}`);
        console.log("=================================");

    } catch (error) {
        console.error(
            "❌ Ошибка при добавлении дат рождения:",
            error
        );
    }
}

