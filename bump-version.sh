#!/bin/bash
# ===================== ОБНОВЛЕНИЕ ВЕРСИИ САЙТА =====================
# Запускай эту команду перед каждым деплоем на GitHub, чтобы сбросить
# кэш браузера у всех посетителей (включая тех, кто добавил сайт на экран телефона).
#
# Использование:
#   bash bump-version.sh
#
# Скрипт сам найдёт текущий номер версии и увеличит его на 1 везде разом:
# в index.html и во всех файлах js/*.js
# ======================================================================

set -e

CURRENT=$(grep -oP "v=\K[0-9]+" index.html | head -1)
if [ -z "$CURRENT" ]; then
  echo "Не нашёл текущую версию в index.html. Проверь вручную."
  exit 1
fi

NEW=$((CURRENT + 1))

echo "Текущая версия: $CURRENT → Новая версия: $NEW"

# Обновляем index.html (style.css?v= и js/main.js?v=)
sed -i "s/v=$CURRENT/v=$NEW/g" index.html

# Обновляем все импорты внутри js/*.js
sed -i "s/\.js?v=$CURRENT'/\.js?v=$NEW'/g" js/*.js

echo "Готово! Версия обновлена на $NEW во всех файлах."
echo "Теперь закоммить и запушь изменения на GitHub."
# ===================== /ОБНОВЛЕНИЕ ВЕРСИИ САЙТА =====================
